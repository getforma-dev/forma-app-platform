//! The composer's typed planning (APP-093; ADR-011 §3 I5): model text in,
//! an [`AdmittedDefinition`] or a coded refusal out. Nothing the model wrote
//! is read as anything but JSON data: the router's reply is decoded into a
//! closed struct whose `choice` must name a catalog entry; a generated reply
//! is decoded strictly as forma-json-v1 (`admission::decode`), its source
//! inputs are replaced by the member's exact readable contracts (so the saved
//! work can bind them and no invented input survives), every data view must
//! be one the engine runs, and the whole content is wrapped in the
//! `app_definition` envelope under the trusted organization and authoring
//! app, digested and judged by `admit_definition`. A refusal is a stable
//! code; the retry loop in [`super::Composer`] feeds back the code alone.
//!
//! APP-132: a generated definition is new content, so after admission it
//! also meets the authoring verdict of contract edition impl-2026-10-31.4
//! (`contracts/validate.py`, `new_content=True`: no duplicate transition, a
//! governed enum field written by a filing create declares its `initial`;
//! Rust admission keeps the stored-document verdict, APP-129 gap 1), and an
//! app with no data view (a records-only app, the clean workspace's first
//! app) offers a form for a create command, so its records can be entered.
use super::Origin;
use crate::{
    admission::{self, digest, AdmissionError, AdmittedDefinition},
    storage::{LibraryApp, ReadableSource},
};
use serde::Deserialize;
use serde_json::{json, Map, Value};

/// Persisted by the server in the admitted definition, so a reload can
/// recover a generated app's origin. Presentation metadata only; never
/// consulted by admission or authorization.
pub const GENERATED_PREFIX: &str = "Generated by Forma.\n";

/// The router's closed reply shape.
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct RouterReply {
    choice: String,
    confidence: String,
    #[serde(default)]
    reason: String,
    #[serde(default)]
    title: Option<String>,
}

/// What the router decided, judged against the catalog it was shown.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum Decision {
    /// Instantiate this library app as it is.
    Retrieve { index: usize },
    /// Start from this library app with the suggested title.
    Adapt { index: usize, title: String },
    /// No library fit: generate.
    Generate,
}

/// Decodes the router's text. Anything outside the closed shape, an unknown
/// id or an unknown confidence is `Generate` (the slow path, never an
/// error the member sees). `confidence` is reported for the log only.
pub fn decide(text: &str, library: &[LibraryApp]) -> (Decision, &'static str) {
    let Some(reply) =
        object(text).and_then(|value| serde_json::from_value::<RouterReply>(value).ok())
    else {
        return (Decision::Generate, "malformed");
    };
    let _ = reply.reason;
    let Some(index) = library.iter().position(|app| app.app == reply.choice) else {
        return (
            Decision::Generate,
            if reply.choice == "none" {
                "none"
            } else {
                "unknown"
            },
        );
    };
    match reply.confidence.as_str() {
        "high" => (Decision::Retrieve { index }, "high"),
        "medium" => {
            let title = reply
                .title
                .as_deref()
                .map(str::trim)
                .filter(|title| !title.is_empty())
                .map(|title| title.chars().take(80).collect())
                .unwrap_or_else(|| library[index].title.clone());
            (Decision::Adapt { index, title }, "medium")
        }
        _ => (Decision::Generate, "low"),
    }
}

/// A planned definition, admitted and ready to draft.
#[derive(Clone, Debug)]
pub struct Planned {
    pub admitted: AdmittedDefinition,
    pub title: String,
    pub origin: Origin,
}

/// Why one generation attempt was refused: admission's code or one of the
/// composer's own (`not_json`, `unknown_source_input`, `not_runnable`,
/// `authoring_rule`, `no_create_form`).
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Refusal {
    pub code: &'static str,
}
impl From<AdmissionError> for Refusal {
    fn from(error: AdmissionError) -> Self {
        Self { code: error.code() }
    }
}

/// The first JSON object in the text (fences and prose around it are
/// dropped), decoded strictly as forma-json-v1 (no floats, no duplicate
/// keys, bounded depth and size).
fn object(text: &str) -> Option<Value> {
    let start = text.find('{')?;
    let end = text.rfind('}')?;
    if end < start {
        return None;
    }
    let value = admission::decode(&text.as_bytes()[start..=end]).ok()?;
    value.is_object().then_some(value)
}

/// Judges one generated reply: parses, pins the source inputs to the
/// member's exact contracts, requires runnable views, envelopes under the
/// trusted scope and admits whole.
pub fn plan_generated(
    text: &str,
    sources: &[ReadableSource],
    organization: &str,
    app: &str,
) -> Result<Planned, Refusal> {
    let mut content = object(text).ok_or(Refusal { code: "not_json" })?;
    pin_sources(&mut content, sources)?;
    // APP-101: only the server writes the adapted marker line the canvas
    // reads its chips from (`transform::ADAPTED_PREFIX`).
    if let Some(rest) = content
        .get("description")
        .and_then(Value::as_str)
        .and_then(|description| description.strip_prefix(super::transform::ADAPTED_PREFIX))
        .map(str::to_owned)
    {
        content["description"] = json!(rest);
    }
    // APP-135: the compose response's origin disappears on reload. Keep it
    // in the admitted bytes, like the existing adapted-description marker.
    // Replace a model-supplied copy rather than accumulating markers on retry.
    if let Some(description) = content.get("description").and_then(Value::as_str) {
        let description = description
            .strip_prefix(GENERATED_PREFIX)
            .unwrap_or(description);
        content["description"] = json!(format!("{GENERATED_PREFIX}{description}"));
    }
    // Admission first, so a malformed document reports admission's code;
    // then the engine's subset over what admission accepted.
    let admitted = admit(&content, organization, app)?;
    require_runnable(&content)?;
    require_authored(&content)?;
    require_entry(&content)?;
    Ok(Planned {
        title: title(&content),
        admitted,
        origin: Origin::Generated,
    })
}

/// The adapted path: a typed patch (title, description) of a library
/// definition's re-admitted content, re-admitted whole under the trusted
/// scope. Nothing else of the library content changes.
pub fn plan_adapted(
    library: &LibraryApp,
    title: &str,
    description: &str,
    organization: &str,
    app: &str,
) -> Result<Planned, Refusal> {
    let mut content = library.content.clone();
    let map = content
        .as_object_mut()
        .ok_or(Refusal { code: "encoding" })?;
    map.insert("title".into(), json!(title));
    // The medium-confidence router path is adapted too, even when no
    // filter transform ran. Persist the same marker format that the canvas
    // uses for transformed definitions, so reopening retains that origin.
    map.insert(
        "description".into(),
        json!(format!(
            "{}App wording updated\n{description}",
            super::transform::ADAPTED_PREFIX
        )),
    );
    let admitted = admit(&content, organization, app)?;
    Ok(Planned {
        title: title.to_owned(),
        admitted,
        origin: Origin::Adapted,
    })
}

/// Every `source` input is replaced by the readable contract of the same
/// id (exact bytes, so its digest equals a bindable revision's); an id
/// outside the member's sources is refused. `records` inputs stay as the
/// model wrote them, for admission to judge.
fn pin_sources(content: &mut Value, sources: &[ReadableSource]) -> Result<(), Refusal> {
    let unknown = Refusal {
        code: "unknown_source_input",
    };
    let Some(inputs) = content.get_mut("inputs").and_then(Value::as_array_mut) else {
        // Admission names the missing or mistyped member.
        return Ok(());
    };
    for input in inputs.iter_mut() {
        let Some(map) = input.as_object_mut() else {
            continue;
        };
        if map.get("kind").and_then(Value::as_str) != Some("source") {
            continue;
        }
        let id = map
            .get("id")
            .and_then(Value::as_str)
            .ok_or_else(|| unknown.clone())?;
        let source = sources
            .iter()
            .find(|source| source.contract.get("id").and_then(Value::as_str) == Some(id))
            .ok_or_else(|| unknown.clone())?;
        *input = source.contract.clone();
    }
    Ok(())
}

/// Every view with a query reads one input through the runnable operators.
pub(crate) fn require_runnable(content: &Value) -> Result<(), Refusal> {
    let runnable = content
        .get("views")
        .and_then(Value::as_array)
        .is_none_or(|views| {
            views
                .iter()
                .all(|view| super::prompt::runnable_view(content, view))
        });
    if runnable {
        Ok(())
    } else {
        Err(Refusal {
            code: "not_runnable",
        })
    }
}

/// The authoring verdict's two definition rules for new content (contract
/// edition impl-2026-10-31.4, `contracts/validate.py` `_definition` with
/// `new_content`), over content admission already accepted: every
/// `(field, from, to)` transition of a command is declared once, and a create
/// with no transitions that may write an enum field another command of the
/// same record schema moves by transitions declares that field's `initial`
/// (storage would otherwise refuse every filing at command time).
pub(crate) fn require_authored(content: &Value) -> Result<(), Refusal> {
    let refused = Err(Refusal {
        code: "authoring_rule",
    });
    let commands = list(content, "commands");
    let moves = |command: &Value| -> Vec<(String, String, String)> {
        list(command, "transitions")
            .iter()
            .map(|transition| {
                let part = |key: &str| {
                    transition
                        .get(key)
                        .and_then(Value::as_str)
                        .unwrap_or_default()
                        .to_owned()
                };
                (part("field_id"), part("from"), part("to"))
            })
            .collect()
    };
    for (slot, command) in commands.iter().enumerate() {
        let declared = moves(command);
        let unique: std::collections::BTreeSet<_> = declared.iter().collect();
        if unique.len() != declared.len() {
            return refused;
        }
        let create = command.get("operation").and_then(Value::as_str) == Some("create");
        if !create || !declared.is_empty() {
            continue;
        }
        let schema = command.get("record_schema_id");
        let governed: std::collections::BTreeSet<String> = commands
            .iter()
            .enumerate()
            .filter(|(other, item)| *other != slot && item.get("record_schema_id") == schema)
            .flat_map(|(_, item)| moves(item).into_iter().map(|(field, _, _)| field))
            .collect();
        let initial: Vec<&str> = list(command, "initial")
            .iter()
            .filter_map(|rule| rule.get("field_id").and_then(Value::as_str))
            .collect();
        if list(command, "writable_fields")
            .iter()
            .filter_map(Value::as_str)
            .any(|field| governed.contains(field) && !initial.contains(&field))
        {
            return refused;
        }
    }
    Ok(())
}

/// An app with no data view offers a form for a create command: otherwise
/// nothing on it can be read or entered.
pub(crate) fn require_entry(content: &Value) -> Result<(), Refusal> {
    let views = list(content, "views");
    let data = views.iter().any(|view| view.get("query").is_some());
    let creates = |id: &str| {
        list(content, "commands").iter().any(|command| {
            command.get("id").and_then(Value::as_str) == Some(id)
                && command.get("operation").and_then(Value::as_str) == Some("create")
        })
    };
    let entry = views.iter().any(|view| {
        view.get("kind").and_then(Value::as_str) == Some("form")
            && view
                .get("command_id")
                .and_then(Value::as_str)
                .is_some_and(creates)
    });
    if data || entry {
        Ok(())
    } else {
        Err(Refusal {
            code: "no_create_form",
        })
    }
}

fn list<'a>(value: &'a Value, key: &str) -> &'a [Value] {
    value
        .get(key)
        .and_then(Value::as_array)
        .map(Vec::as_slice)
        .unwrap_or_default()
}

/// The envelope under the trusted scope (organization and authoring app from
/// the request, never from the model), the content's digest, admission.
pub(crate) fn admit(
    content: &Value,
    organization: &str,
    app: &str,
) -> Result<AdmittedDefinition, Refusal> {
    let canonical = admission::encode(content)?;
    let identity = digest::digest(digest::APP_DEFINITION, &canonical);
    let mut envelope = Map::new();
    envelope.insert("kind".into(), json!("app_definition"));
    envelope.insert("schema_version".into(), json!(1));
    envelope.insert("organization_id".into(), json!(organization));
    envelope.insert("app_id".into(), json!(app));
    envelope.insert("revision_id".into(), json!(app));
    envelope.insert("content".into(), content.clone());
    envelope.insert("digest".into(), json!(identity));
    let bytes = admission::encode(&Value::Object(envelope))?;
    Ok(admission::admit_definition(&bytes)?)
}

fn title(content: &Value) -> String {
    content
        .get("title")
        .and_then(Value::as_str)
        .unwrap_or("Composed app")
        .to_owned()
}
