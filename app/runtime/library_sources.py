"""Prebuilt library sources (ADR-011 pitch, APP-094): labeled synthetic CSVs normalized to Parquet.

The pitch's library apps (`contracts/fixtures/library/*.json`, catalog
`contracts/fixtures/library/catalog.json`) each read one source input. This
module is the mapping from a library CSV to the contract-typed normalized
revision the governed engine reads (`app/runtime/query_engine.py`), written
exactly as the operator's `upload-sources` adapter writes the Northstar
revision (`app/operator/operator.py` `normalize`): DuckDB 2.0.0, one thread,
`FORMAT PARQUET, COMPRESSION ZSTD, ROW_GROUP_SIZE 100000`, rows ordered by the
`time` field then the original record (ADR-009 D9.3), so the same CSV bytes
always produce the same `normalized_digest`, which is what the library fixture
pins and what the engine re-checks before every run.

Column typing per contract value type (the engine's `query_engine.py` reads
the same table through the request's `fields`):

| contract type | CSV cell | Parquet column |
| --- | --- | --- |
| text, enum | the text (an enum cell must be a declared value) | VARCHAR |
| boolean | `true` / `false` | BOOLEAN |
| integer | canonical integer | BIGINT |
| money (USD, exponent 2) | decimal dollars with exactly two places, `1250.00` | BIGINT minor units |
| decimal (scale s) | decimal text with at most s places | BIGINT coefficient at scale s |
| date | `YYYY-MM-DD` | DATE |
| timestamp | `YYYY-MM-DDTHH:MM:SSZ` | TIMESTAMP (naive UTC) |

An empty cell is NULL only for a nullable field; anything else refuses the
whole file. No float ever enters: money and decimals are parsed as integer
text. Nothing here is customer data: every row is generated by
`contracts/make_library.py` and labeled synthetic in the catalog.

Operator use (local demo or the APP-096 deploy):

    python3 app/runtime/library_sources.py build --organization <org> --cache-root <dir>
        writes <dir>/o/<org>/<source>.<revision>.parquet (mode 0400) for every
        library source and prints each revision's digests; a digest that differs
        from the catalog's pin refuses (nothing is written for that source).
    python3 app/runtime/library_sources.py plan --organization <org>
        prints the ADR-009 B1 object keys (`o/<org>/s/<source>/r/<revision>/
        {original,part.parquet}`) the deploy uploads; this module never
        touches AWS.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
# APP-113 review: the one normalization (typing table, order, round trip) is the
# service image's box normalizer; this module only maps the library onto it.
from box_normalize import (  # noqa: E402
    Refused, column_type, normalize, ordered_rows, require, rows_of, scaled_integer, sha256, typed_value,
)

__all__ = ["Refused", "column_type", "normalize", "ordered_rows", "require", "rows_of", "scaled_integer", "sha256",
           "typed_value", "load_catalog", "sources_of", "cache_path", "object_keys", "build", "main"]

REPOSITORY = Path(__file__).resolve().parents[2]
LIBRARY = REPOSITORY / "contracts" / "fixtures" / "library"
CATALOG = LIBRARY / "catalog.json"
UUID = re.compile(r"[0-9a-f]{8}-[0-9a-f]{4}-[47][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}")


def load_catalog(path=CATALOG):
    catalog = json.loads(Path(path).read_text())
    require(catalog.get("schema_version") == 1 and catalog.get("synthetic") is True, "catalog_refused")
    return catalog


def sources_of(catalog):
    """Every library source once (an app may share a source), keyed by source id."""
    found = {}
    for app in catalog["apps"]:
        for source in app["sources"]:
            previous = found.setdefault(source["source_id"], source)
            require(previous == source, "catalog_source_conflict")
    return found


def cache_path(cache_root, organization, source_id, revision_id):
    return Path(cache_root) / "o" / organization / ("%s.%s.parquet" % (source_id, revision_id))


def object_keys(organization, source):
    prefix = "o/%s/s/%s/r/%s/" % (organization, source["source_id"], source["revision_id"])
    return {"original": prefix + "original", "part.parquet": prefix + "part.parquet"}


def build(organization, cache_root, catalog=None, library=LIBRARY):
    """Normalizes every library source into `cache_root` for `organization`; the digests must equal the catalog's."""
    require(UUID.fullmatch(organization) is not None, "organization_refused")
    catalog = catalog or load_catalog(Path(library) / "catalog.json")
    directory = Path(cache_root) / "o" / organization
    directory.mkdir(mode=0o700, parents=True, exist_ok=True)
    for path in (Path(cache_root), Path(cache_root) / "o", directory):
        os.chmod(path, 0o700)
    records = []
    for source in sources_of(catalog).values():
        data = (Path(library) / source["csv"]).read_bytes()
        require(sha256(data) == source["content_digest"], "content_digest_mismatch")
        target = cache_path(cache_root, organization, source["source_id"], source["revision_id"])
        staging = target.with_name(".library-" + target.name)
        normalized, count = normalize(source["input_contract"], data, staging)
        if normalized != source["normalized_digest"] or count != source["row_count"]:
            staging.unlink()
            raise Refused("normalized_digest_mismatch")
        if target.exists():
            require(sha256(target.read_bytes()) == normalized, "cached_differs")
            staging.unlink()
        else:
            os.chmod(staging, 0o400)
            os.replace(staging, target)
        records.append({"input_id": source["input_id"], "source_id": source["source_id"], "revision_id": source["revision_id"],
                        "content_digest": source["content_digest"], "normalized_digest": normalized, "row_count": count,
                        "path": str(target), "objects": object_keys(organization, source)})
    return records


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    b = sub.add_parser("build")
    b.add_argument("--organization", required=True)
    b.add_argument("--cache-root", required=True)
    p = sub.add_parser("plan")
    p.add_argument("--organization", required=True)
    args = parser.parse_args(argv)
    try:
        if args.command == "build":
            result = {"command": "build", "organization_id": args.organization, "sources": build(args.organization, args.cache_root)}
        else:
            require(UUID.fullmatch(args.organization) is not None, "organization_refused")
            catalog = load_catalog()
            result = {"command": "plan", "organization_id": args.organization, "synthetic": True,
                      "sources": [{"input_id": s["input_id"], "source_id": s["source_id"], "revision_id": s["revision_id"], "csv": s["csv"],
                                   "content_digest": s["content_digest"], "normalized_digest": s["normalized_digest"], "row_count": s["row_count"],
                                   "objects": object_keys(args.organization, s)} for s in sources_of(catalog).values()]}
    except Refused as refusal:
        print(json.dumps({"refused": str(refusal)}), file=sys.stderr)
        return 1
    print(json.dumps(result, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
